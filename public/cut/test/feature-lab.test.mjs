import assert from 'node:assert/strict';
import {rmsWindows,detectSilences,detectBeats,frameDifference,detectSceneCuts,sourceToProjectTime,normalizeMarkers,splitAtMarkers,searchTranscript,parseEditCommand,MAX_SPLITS} from '../feature-lab-core.mjs';
import {FEATURE_LAB_CATALOG,featureSummary} from '../feature-lab-catalog.mjs';
import {projectAssetIds} from '../project-archive.mjs';
const audio=Float32Array.from({length:2500},(_,i)=>i%250<50?.8:.002);
const buffer={sampleRate:1000,numberOfChannels:1,length:audio.length,getChannelData:()=>audio};
const windows=rmsWindows(buffer,{stepSeconds:.04});
assert.ok(windows.length>=15);
assert.ok(windows[0].rms>.3);
assert.ok(detectBeats(windows).length>=2,'percussive onset candidates');
const quiet=Array.from({length:50},(_,i)=>({time:i*.05,rms:i>=10&&i<28?.001:.4}));
const silences=detectSilences(quiet,{thresholdDb:-35,minSeconds:.5});
assert.equal(silences.length,1);
assert.ok(silences[0].end-silences[0].start>=.85);
assert.equal(frameDifference(new Uint8ClampedArray([0,0,0,255]),new Uint8ClampedArray([255,255,255,255])),1);
assert.equal(detectSceneCuts([{time:0,pixels:new Uint8ClampedArray([0,0,0,255])},{time:1,pixels:new Uint8ClampedArray([255,255,255,255])}]).length,1);
assert.equal(sourceToProjectTime(5,{start:2,end:8,speed:2},1),2.5);
assert.equal(sourceToProjectTime(5,{start:2,end:8,speed:2,reverse:true},1),2.5);
assert.equal(sourceToProjectTime(20,{start:2,end:8,speed:2},1),null);
assert.equal(normalizeMarkers([{time:1,kind:'beat'},{time:1.001,kind:'beat'}]).length,1);
const clip={id:'a',assetId:'video',type:'video',start:0,end:6,speed:1,filter:'none'};
const cuts=splitAtMarkers([clip],[{time:2.5},{time:4}]);assert.equal(cuts.count,2);assert.equal(cuts.clips.length,3);assert.equal(clip.start,0);assert.equal(clip.end,6);
assert.ok(MAX_SPLITS<=50);
assert.equal(searchTranscript([{start:1,text:'青い夢'},{start:2,text:'夜の光'}],'夜').length,1);
assert.equal(parseEditCommand('3秒に分割').type,'split');
assert.equal(parseEditCommand('速度を2倍').speed,2);
assert.equal(parseEditCommand('9:16に').ratio,'9:16');
assert.equal(parseEditCommand('5秒に移動').type,'seek');
assert.equal(parseEditCommand('テキスト「こんにちは」を追加').text,'こんにちは');
assert.equal(parseEditCommand('ミュート').type,'mute');
assert.equal(parseEditCommand('全部AIで生成'),null);
assert.equal(FEATURE_LAB_CATALOG.length,42);
const count=featureSummary();assert.equal(Object.values(count).reduce((a,b)=>a+b,0),42);
assert.equal(count.active,4);assert.equal(count.backend,21);assert.equal(count.research,9);
assert.deepEqual(new Set(projectAssetIds({clips:[{assetId:'main'}],editBranches:[{key:'A',snapshot:{clips:[{assetId:'branch-only'}],overlays:[],audioTracks:[]}}]})),new Set(['main','branch-only']),'branch-only asset survives portable archive');
console.log('feature-lab analysis and 42-feature catalog PASS');
