import assert from 'node:assert/strict';
import {FILTER_TYPES,filterStyle,composedFilterStack,filterCount,addFilter,moveFilter,cloneFilterStack,MAX_FILTERS} from '../filter-stack.mjs';
assert.equal(Object.keys(FILTER_TYPES).length,12);
assert.equal(filterStyle('monochrome',0),'');
assert.equal(filterStyle('monochrome',1),'grayscale(1)');
assert.equal(filterStyle('invert',1),'invert(1)');
assert.equal(filterStyle('brightness',.5),'brightness(1.3)');
assert.equal(filterStyle('unknown',.5),'');
assert.equal(filterStyle('blur',Infinity),'');
const initial=[{id:'a',type:'monochrome',amount:1,enabled:true},{id:'b',type:'invert',amount:1,enabled:true}];
assert.equal(composedFilterStack(initial),'grayscale(1) invert(1)');
assert.equal(composedFilterStack(moveFilter(initial,'b',0)),'invert(1) grayscale(1)');
assert.equal(initial[0].id,'a','reordering must not mutate existing array');
initial[0].enabled=false;
assert.equal(composedFilterStack(initial),'invert(1)');
assert.equal(filterCount(initial),1);
assert.equal(filterCount([{type:'unknown'}]),0);
const copied=cloneFilterStack(initial);copied[0].amount=.1;
assert.equal(initial[0].amount,1,'deep-clone for copying edits');
const two=addFilter([], 'sepia', .6, 'one');
assert.deepEqual(two,[{id:'one',type:'sepia',amount:.6,enabled:true}]);
assert.throws(()=>addFilter(two,'not-exist'),/不明/);
const limit=Array.from({length:MAX_FILTERS},(_,i)=>({id:String(i),type:'monochrome',amount:1}));
assert.throws(()=>addFilter(limit,'cool'),/16個/);
assert.equal(composedFilterStack(null),'');
assert.equal(filterStyle('cool',1).includes('hue-rotate'),true);
console.log('filter-stack tests PASS');
