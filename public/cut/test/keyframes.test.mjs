import assert from 'node:assert/strict';
import {clipTransform} from '../keyframes.mjs';
const clip={zoom:1,rotation:0,x:.5,y:.5,opacity:1,keyframes:[{time:0,zoom:1,x:0,opacity:0},{time:2,zoom:3,x:1,opacity:1}]};
assert.equal(clipTransform(clip,0).x,0);
assert.equal(clipTransform(clip,1).zoom,2);
assert.equal(clipTransform(clip,1).opacity,.5);
assert.equal(clipTransform(clip,2).x,1);
assert.equal(clipTransform({},1).zoom,1);
clip.easing='ease-in-out';
assert.ok(clipTransform(clip,.5).x < .25);
clip.keyframes.reverse();assert.equal(clipTransform(clip,1).zoom,2);
console.log('base keyframe interpolation: PASS');
