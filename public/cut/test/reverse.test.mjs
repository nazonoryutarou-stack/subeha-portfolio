import assert from 'node:assert/strict';
import {locate,splitAt,duration} from '../timeline.mjs';
const clips=[{id:'r',start:1,end:5,speed:1,reverse:true}];
assert.equal(locate(clips,0).mediaTime,5);
assert.equal(locate(clips,2).mediaTime,3);
assert.ok(locate(clips,3.999).mediaTime>1);
const cut=splitAt(clips,1.5);
assert.ok(cut);
assert.equal(cut.first.start,3.5);
assert.equal(cut.first.end,5);
assert.equal(cut.second.start,1);
assert.equal(cut.second.end,3.5);
assert.equal(duration(cut.clips),4);
assert.equal(locate(cut.clips,0).mediaTime,5);
assert.equal(locate(cut.clips,1.5).mediaTime,3.5);
assert.equal(locate(cut.clips,3.5).mediaTime,1.5);
const withKeys=[{id:'k',start:0,end:10,speed:1,reverse:true,keyframes:[{time:0,zoom:1},{time:10,zoom:2}]}];
const split=splitAt(withKeys,4);
split.first.keyframes[0].zoom=99;
assert.equal(withKeys[0].keyframes[0].zoom,1);
console.log('reverse time mapping and split tests: PASS');
