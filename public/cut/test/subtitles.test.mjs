import assert from 'node:assert/strict';
import {parseTimestamp,parseSRT,parseVTT,parseWhisperJSON,activeCue,exportSRT,parseSubtitleFile,drawCaptions} from '../subtitles.mjs';
assert.equal(parseTimestamp('01:02:03,250'),3723.25);
assert.equal(parseTimestamp('01:23.500'),83.5);
assert.equal(parseTimestamp('00:01:00.000'),60);
assert.ok(Number.isNaN(parseTimestamp('not-time')));
const srt='1\r\n00:00:00,200 --> 00:00:01,500\r\nこんにちは\r\n\r\n2\r\n00:00:02,000 --> 00:00:03,000\r\n<b>世界</b>';
const cues=parseSRT(srt);assert.equal(cues.length,2);assert.equal(cues[1].text,'世界');
assert.equal(activeCue(cues,.5).text,'こんにちは');assert.equal(activeCue(cues,1.6),null);
assert.equal(parseVTT('WEBVTT\n\nNOTE hello\n\n00:00:00.200 --> 00:00:01.500 align:center\nHello')[0].text,'Hello');
assert.equal(parseSubtitleFile('WEBVTT\n\n00:00:00.200 --> 00:00:01.500\nHey','hello.vtt')[0].start,.2);
assert.equal(parseWhisperJSON(JSON.stringify({segments:[{start:1.2,end:2.3,text:'字幕'}]}))[0].end,2.3);
assert.equal(parseWhisperJSON({segments:[{t0:123,t1:230,text:'centiseconds'}]})[0].start,1.23);
assert.equal(parseWhisperJSON({transcription:[{timestamps:{from:'00:00:03.000',to:'00:00:04.000'},text:'音声'}]})[0].text,'音声');
assert.equal(parseSRT(srt,{offset:2})[0].start,2.2);
assert.equal(parseSRT(exportSRT(cues)).length,2);
assert.throws(()=>parseWhisperJSON('{"wrong":true}'),/segments/);
const calls=[];
const ctx={save(){calls.push('save');},restore(){calls.push('restore');},measureText(x){return {width:x.length*20}},beginPath(){},roundRect(){},fill(){},fillText(t){calls.push(t);},strokeText(){},set font(v){},set textAlign(v){},set textBaseline(v){},set fillStyle(v){},set strokeStyle(v){},set lineWidth(v){},set lineJoin(v){}};
drawCaptions(ctx,{width:720,height:1280},{captions:cues},.5);
assert.ok(calls.includes('こんにちは'));assert.equal(calls.at(-1),'restore');
