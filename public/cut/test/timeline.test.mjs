import assert from 'node:assert/strict';
import {clipLength,duration,locate,splitAt,clampTime,RATIOS,formatClock,safeName} from '../timeline.mjs';
const clips=[{id:'1',start:2,end:10,speed:2},{id:'2',start:0,end:5,speed:1}];
assert.equal(clipLength(clips[0]),4);
assert.equal(duration(clips),9);
assert.equal(locate(clips,0).mediaTime,2);
assert.equal(locate(clips,1.5).mediaTime,5);
assert.equal(locate(clips,5).clip.id,'2');
assert.equal(locate(clips,5).mediaTime,1);
assert.equal(locate(clips,100).clip.id,'2');
assert.equal(locate([],1),null);
assert.equal(clampTime(999,clips),9);
assert.equal(formatClock(69.12),'01:09');
assert.equal(safeName('bad/name.mp4'),'bad_name.mp4');
assert.deepEqual(RATIOS['9:16'],[720,1280]);
assert.deepEqual(RATIOS['4:5'],[960,1200]);
assert.deepEqual(RATIOS['3:4'],[960,1280]);
assert.deepEqual(RATIOS['21:9'],[1260,540]);
const split=splitAt(clips,3);
assert.ok(split);
assert.equal(split.clips.length,3);
assert.equal(split.clips[0].end,8);
assert.equal(split.clips[1].start,8);
assert.equal(duration(split.clips),9);
assert.equal(splitAt(clips,0),null);
console.log('timeline tests: PASS');
