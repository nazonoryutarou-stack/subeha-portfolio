import assert from 'node:assert/strict';
import {timelineScroll,timelineTime,rulerStep,clipTrim,moveClip,applyOverlayTransform} from '../touch-edit.mjs';
assert.equal(timelineScroll(3,36),108);
assert.equal(timelineTime(108,36,100),3);
assert.equal(timelineTime(1000,36,9),9);
assert.equal(rulerStep(20),5);
assert.equal(rulerStep(70),1);
const a={id:'a',start:2,end:12,speed:2};
assert.equal(clipTrim(a,'left',40,20,30).start,6);
assert.equal(clipTrim(a,'right',20,20,30).end,14);
assert.equal(clipTrim(a,'left',999,20,30).start,11.76);
const r={...a,reverse:true};
assert.equal(clipTrim(r,'left',40,20,30).end,8);
assert.equal(clipTrim(r,'right',20,20,30).start,0);
assert.equal(a.start,2);
const clips=[{id:'a'},{id:'b',transitionIn:{type:'dissolve',duration:.5}},{id:'c'}];
const moved=moveClip(clips,'c',1);
assert.deepEqual(moved.map(c=>c.id),['a','c','b']);
assert.equal(moved[1].transitionIn.type,'none');
assert.equal(moved[2].transitionIn.type,'none');
assert.equal(clips[1].transitionIn.type,'dissolve');
const layer={x:.5,y:.5,scale:.7,start:1,duration:6,keyframes:[{time:1,x:.2,y:.4,scale:.5}]};
const transformed=applyOverlayTransform(layer,2,{x:.8});
assert.equal(transformed.keyframes[0].x,.8);
assert.equal(layer.keyframes[0].x,.2);
const inserted=applyOverlayTransform(layer,3,{x:.7,y:.6});
assert.equal(inserted.keyframes.length,2);
assert.equal(inserted.keyframes[1].time,2);
assert.equal(applyOverlayTransform({x:.5,start:0,duration:3},2,{x:.8}).x,.8);
console.log('touch timeline geometry: PASS');
